export const COLOR_IDS = Object.keys(COLOR_THEME);

export const getTheme = (colorId) => COLOR_THEME[colorId] || COLOR_THEME.purple;

export const hexToColorId = (hex) => {
  const match = Object.entries(COLOR_THEME).find(
    ([, theme]) => theme.hex.toLowerCase() === (hex || "").toLowerCase()
  );
  return match ? match[0] : "purple";
};
